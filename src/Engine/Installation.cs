using System.Diagnostics;
using System.Runtime.InteropServices;
using System.Security.Cryptography;
using System.Security.Principal;
using System.Text;
using Microsoft.Win32;

namespace Ros2Setup;

public sealed class Installation : IInstallation, IDisposable
{
    private const string Release = "release-humble-20260220";
    private const string Workload = "Microsoft.VisualStudio.Workload.VCTools";
    private const string Compiler = "Microsoft.VisualStudio.Component.VC.Tools.x86.x64";
    private const string Sdk = "Microsoft.VisualStudio.Component.Windows10SDK.19041";
    private const string LauncherHeader = "rem Generated by ROS 2 Humble Setup";
    private readonly List<(Step Step, Func<Task> Run)> _plan = [];
    private readonly List<string> _reused = [];
    private readonly Options _options;
    private readonly string _destination;
    private readonly string _workspace;
    private readonly string _payload;
    private readonly string _mirror;
    private readonly bool _offline;
    private readonly bool _hadRosAtReview;
    private readonly string _scratch = Path.Combine(Path.GetTempPath(), $"ros2-setup-{Guid.NewGuid():N}");
    private readonly string _log = Path.Combine(Path.GetTempPath(), $"ros2-setup-{Guid.NewGuid():N}.log");
    private FileStream? _lease;
    private RosEnvironment? _environment;
    private int _next;

    public Installation(Options options, string artifactDirectory, bool container = false, bool forceOffline = false)
    {
        ValidatePlatform(container);
        _options = options;
        _destination = ValidateDestination(options.Destination);
        _workspace = Path.Combine(_destination, ".ros2-dependencies", ".pixi", "envs", "default");
        _offline = forceOffline || File.Exists(Path.Combine(artifactDirectory, "offline.json"));
        _payload = _offline ? Path.Combine(artifactDirectory, "payload") : _scratch;
        _mirror = Path.Combine(_payload, "conda");
        var receiver = options.WalkableOrReceiver ? new ReceiverWorkspace(_destination, Launcher, _log) : null;
        receiver?.ValidateWorkspace();
        var receiverSource = receiver is null ? null : Path.Combine(_payload, ReceiverSources.OfflineFileName);

        var ros = Get("ros");
        var pixi = Get("pixi");
        var vc = Get("vc");
        var vs = Get("vs");
        var hasRos = ExistingRos();
        _hadRosAtReview = hasRos;
        var hasVc = HasVcRuntime();
        var hasVs = options.Development && FindBuildTools();
        var environmentNeeded = !ExistingEnvironment();
        var needed = new List<Payload>();
        if (!hasRos || environmentNeeded) needed.Add(ros);
        if (environmentNeeded) needed.Add(pixi);
        if (!hasVc) needed.Add(vc);
        if (options.Development && !hasVs && !_offline) needed.Add(vs);

        // Review-time checks are read-only. Hashing stays in the first confirmed offline action.
        if (_offline)
        {
            foreach (var asset in needed)
                RequireFile(AssetPath(asset));
            if (options.Development && !hasVs)
                RequireFile(Path.Combine(_payload, "vs-layout", "layout.sha256"));
            if (receiverSource is not null) RequireFile(receiverSource);
            Add("Verify offline payloads", $"Check the selected package files against SHA-256 checksums in {_payload}.",
                async () =>
                {
                    foreach (var asset in needed) await Payloads.VerifyAsync(AssetPath(asset), asset.Sha256);
                    if (receiverSource is not null) ReceiverSources.VerifyArchive(receiverSource);
                    if (environmentNeeded)
                    {
                        _environment = RosEnvironment.FromArchive(AssetPath(ros));
                        foreach (var asset in _environment.Select(_options))
                            await Payloads.VerifyAsync(RosEnvironment.MirrorPath(_mirror, asset), asset.Sha256);
                    }
                    if (options.Development && !hasVs) await VerifyLayoutAsync(vs);
                });
        }
        else
        {
            foreach (var asset in needed)
            {
                Add($"Download {asset.File}", $"Download from {asset.Url}\nVerify SHA-256 and save to {_scratch}.",
                    () => WindowsOperations.DownloadAsync(asset, AssetPath(asset)));
            }
            if (environmentNeeded)
            {
                Add("Download pinned ROS dependencies",
                    $"Download the selected Python and native packages from conda-forge using the ROS release lock. Verify SHA-256 and cache them in {_mirror}.",
                    DownloadEnvironmentAsync);
            }
        }

        if (hasVc) _reused.Add("Microsoft Visual C++ x64 runtime");
        else Add("Install Microsoft Visual C++ x64 runtime",
            $"{AssetPath(vc)} /install /quiet /norestart\nInstalls the system-wide Microsoft Visual C++ runtime.",
            () => WindowsOperations.RunAsync(AssetPath(vc), ["/install", "/quiet", "/norestart"], _log,
                NeedsElevation(), null, 1641, 3010), admin: true);

        if (hasRos) _reused.Add($"ROS 2 Humble Patch Release 14 in {_destination}");
        else Add("Extract ROS 2 Humble",
            $"Extract the verified archive to {_destination}, including the Cyclone DDS and Fast DDS libraries.",
            () => Task.Run(() => ExtractRos(AssetPath(ros))));

        if (environmentNeeded)
        {
            var description = "Set up the pinned Python 3.10 environment and native runtime dependencies.";
            if (options.Development) description += " Include CMake, colcon, and C++ headers.";
            else if (receiver is not null) description += " Include the Python build tools for the WalkableOR receiver.";
            if (options.Visualization || options.Graphviz) description += " Include Qt, RViz dependencies, and PyQt.";
            if (options.Graphviz) description += " Include Graphviz and its Python bindings.";
            if (options.OpenCv) description += " Include OpenCV and its Python bindings.";
            if (Directory.Exists(_workspace)) description += " Synchronize installed packages with the selected components.";
            Add("Install selected ROS dependencies",
                $"{description}\nPixi installs from local files into {_workspace}.",
                () => InstallEnvironmentAsync(pixi));
        }
        else _reused.Add($"Pinned ROS dependencies in {_workspace}");

        if (hasVs) _reused.Add("Visual Studio 2019 C++ toolchain and Windows SDK");
        else if (options.Development)
        {
            var executable = _offline ? Path.Combine(_payload, "vs-layout", vs.File) : AssetPath(vs);
            var arguments = BuildToolsArguments(_offline);
            Add("Install Visual Studio 2019 C++ Build Tools",
                $"{executable} {string.Join(' ', arguments)}\nInstalls the v142 compiler and Windows SDK system-wide.",
                () => WindowsOperations.RunAsync(executable, arguments, _log, NeedsElevation(), null, 1641, 3010),
                admin: true);
        }

        var patched = Path.Combine(_destination, ".ros2-launchers");
        if (!File.Exists(patched))
        {
            Add("Set Python paths in ROS scripts",
                $"Run the release's preinstall_setup_windows.py using {_workspace}\\python.exe. This updates ROS script and setup-file paths in {_destination}.",
                PatchRosAsync);
        }

        Add("Configure the ROS command prompt", $"Write {Launcher}\nSet RMW_IMPLEMENTATION={options.Rmw} for that shell.",
            () => Task.Run(WriteLauncher));
        if (options.StartMenu) AddShortcut("Start menu", Environment.SpecialFolder.Programs);
        if (options.Desktop) AddShortcut("desktop", Environment.SpecialFolder.DesktopDirectory);
        Add("Verify the ROS command prompt",
            $"Load {Launcher}, run ros2 --help, and initialize a Python node with {options.Rmw}.",
            VerifyRosAsync);
        if (receiver is not null) AddReceiverSteps(receiver, receiverSource!);
    }

    public IReadOnlyList<Step> Steps => _plan.Select(item => item.Step).ToArray();
    public IReadOnlyList<string> Reused => _reused;
    public string Launcher => Path.Combine(_destination, "ros-humble.cmd");
    public string? ReceiverCompletionMessage
    {
        get
        {
            if (!_options.WalkableOrReceiver) return null;
            var path = ReceiverLayout.ConfigPath(_destination);
            return ReceiverLayout.CompletionMessage(path, _options.WalkableOrProject is not null, File.Exists(path));
        }
    }
    public string? LogPath => File.Exists(_log) ? _log : null;

    public async Task ExecuteAsync(int index)
    {
        if (index != _next) throw new InvalidOperationException("Steps must be run in order.");
        var (step, run) = _plan[index];
        try
        {
            if (index == 0)
            {
                var hash = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(_destination.ToUpperInvariant())));
                _lease = new FileStream(Path.Combine(Path.GetTempPath(), $"ros2-setup-{hash}.lock"),
                    FileMode.OpenOrCreate, FileAccess.ReadWrite, FileShare.None, 1, FileOptions.DeleteOnClose);
                if (ExistingRos() != _hadRosAtReview)
                    throw new IOException("The destination changed after review. Reopen setup to review an updated plan.");
                if (!_offline) Directory.CreateDirectory(_scratch);
            }
            await File.AppendAllTextAsync(_log, $"[{DateTimeOffset.Now:O}] {step.Title}\n{step.Detail}\n");
            await run();
            _next++;
            await File.AppendAllTextAsync(_log, "Completed.\n\n");
        }
        catch (Exception error)
        {
            await File.AppendAllTextAsync(_log, $"{error.Message}\n");
            throw;
        }
    }

    private void Add(string title, string detail, Func<Task> run, bool admin = false) =>
        _plan.Add((new Step(title, detail, admin), run));

    private static Payload Get(string group) => Payloads.All.Single(asset => asset.Group == group);
    private string AssetPath(Payload asset) => Path.Combine(_payload, asset.File);
    private string EnvironmentStamp =>
        $"{Release}: {_options.Development} {_options.Visualization || _options.Graphviz} {_options.Graphviz} {_options.OpenCv}" +
        (_options.WalkableOrReceiver && !_options.Development ? " walkableor-colcon" : "");
    private string EnvironmentStampPath => Path.Combine(_destination, ".ros2-environment");

    private bool ExistingRos()
    {
        if (!Directory.Exists(_destination)) return false;
        if (!Directory.EnumerateFileSystemEntries(_destination).Any()) return false;
        var marker = Path.Combine(_destination, ".ros2-release");
        if (File.Exists(marker) && File.ReadAllText(marker) == Release &&
            File.Exists(Path.Combine(_destination, "local_setup.bat"))) return true;
        throw new IOException($"Choose an empty folder. The installer cannot reuse the existing files in {_destination}.");
    }

    private bool ExistingEnvironment() =>
        File.Exists(EnvironmentStampPath) && File.ReadAllText(EnvironmentStampPath) == EnvironmentStamp &&
        File.Exists(Path.Combine(_workspace, "python.exe")) &&
        File.Exists(Path.Combine(_workspace, "Library", "bin", "libssl-1_1-x64.dll")) &&
        (!_options.Development || File.Exists(Path.Combine(_workspace, "Library", "bin", "cmake.exe"))) &&
        (!_options.WalkableOrReceiver || File.Exists(Path.Combine(_workspace, "Scripts", "colcon.exe"))) &&
        (!_options.Graphviz || File.Exists(Path.Combine(_workspace, "Library", "bin", "dot.exe")));

    private async Task DownloadEnvironmentAsync()
    {
        _environment = RosEnvironment.FromArchive(AssetPath(Get("ros")));
        var assets = _environment.Select(_options);
        await Parallel.ForEachAsync(assets, new ParallelOptions { MaxDegreeOfParallelism = 5 },
            async (asset, _) =>
            {
                var path = RosEnvironment.MirrorPath(_mirror, asset);
                Directory.CreateDirectory(Path.GetDirectoryName(path)!);
                await WindowsOperations.DownloadAsync(asset, path);
            });
    }

    private void ExtractRos(string archive)
    {
        var parent = Path.GetDirectoryName(_destination)!;
        Directory.CreateDirectory(parent);
        var stage = Path.Combine(parent, $".ros2-staging-{Guid.NewGuid():N}");
        Directory.CreateDirectory(stage);
        try
        {
            WindowsOperations.ExtractZip(archive, stage);
            var root = Path.Combine(stage, "ros2-windows");
            foreach (var file in new[] { "local_setup.bat", "pixi.toml", "pixi.lock",
                @"bin\rmw_cyclonedds_cpp.dll", @"bin\ddsc.dll", @"bin\rmw_fastrtps_cpp.dll" })
                RequireFile(Path.Combine(root, file));
            File.WriteAllText(Path.Combine(root, ".ros2-release"), Release);
            if (Directory.Exists(_destination)) Directory.Delete(_destination);
            Directory.Move(root, _destination);
        }
        finally
        {
            Directory.Delete(stage, recursive: true);
        }
    }

    private async Task InstallEnvironmentAsync(Payload pixi)
    {
        // Both variants install exclusively from verified local packages. Keep the original release lock intact.
        var environment = _environment ?? throw new InvalidOperationException("ROS package sources have not been verified.");
        File.Delete(EnvironmentStampPath);
        var localChannel = new Uri(_mirror + Path.DirectorySeparatorChar).AbsoluteUri;
        // Pixi looks for a sibling pixi.lock and installs under the manifest directory.
        var generated = Path.Combine(_destination, ".ros2-dependencies");
        Directory.CreateDirectory(generated);
        var config = $"[workspace]\nname = \"ros2_humble_dependencies\"\nchannels = [\"{localChannel}\"]\nplatforms = [\"win-64\"]\nconda-pypi-map = false\n";
        var generatedManifest = Path.Combine(generated, "pixi.toml");
        File.WriteAllText(generatedManifest, config);
        File.WriteAllText(Path.Combine(generated, "pixi.lock"), environment.LocalLock(_options, _mirror));
        var start = new ProcessStartInfo(AssetPath(pixi))
        {
            WorkingDirectory = generated, UseShellExecute = false, CreateNoWindow = true,
            RedirectStandardOutput = true, RedirectStandardError = true
        };
        foreach (var arg in new[] { "install", "--manifest-path", generatedManifest, "--frozen", "--offline" })
            start.ArgumentList.Add(arg);
        start.Environment["PIXI_CACHE_DIR"] = Path.Combine(_scratch, "pixi-cache");
        start.Environment["PIXI_HOME"] = Path.Combine(_scratch, "pixi-home");
        start.Environment["PIXI_NO_PROGRESS"] = "true";
        await WindowsOperations.RunAsync(start, _log);
        RequireFile(Path.Combine(_workspace, "python.exe"));
        File.WriteAllText(EnvironmentStampPath, EnvironmentStamp);
    }

    private async Task PatchRosAsync()
    {
        var start = new ProcessStartInfo(Path.Combine(_workspace, "python.exe"))
        {
            WorkingDirectory = _destination, UseShellExecute = false, CreateNoWindow = true,
            RedirectStandardOutput = true, RedirectStandardError = true
        };
        start.Environment["CONDA_PREFIX"] = _workspace;
        start.Environment.Remove("PYTHONHOME");
        start.Environment.Remove("PYTHONPATH");
        start.ArgumentList.Add(Path.Combine(_destination, "preinstall_setup_windows.py"));
        await WindowsOperations.RunAsync(start, _log);
        File.WriteAllText(Path.Combine(_destination, ".ros2-launchers"), Release);
    }

    private void WriteLauncher()
    {
        if (File.Exists(Launcher) && !File.ReadLines(Launcher).Take(2).Contains(LauncherHeader))
            throw new IOException($"A different launcher already exists at {Launcher}.");
        var prefix = Path.GetRelativePath(_destination, _workspace);
        var lines = new List<string>
        {
            "@echo off", LauncherHeader,
            $"set \"CONDA_PREFIX=%~dp0{prefix}\"",
            "set \"COLCON_PYTHON_EXECUTABLE=%CONDA_PREFIX%\\python.exe\"",
            "set \"PYTHONHOME=\"",
            "set \"PYTHONPATH=\"",
            "set \"PATH=%CONDA_PREFIX%;%CONDA_PREFIX%\\Library\\bin;%CONDA_PREFIX%\\Scripts;%PATH%\"",
            "set \"CMAKE_PREFIX_PATH=%CONDA_PREFIX%\\Library;%CMAKE_PREFIX_PATH%\"",
            "set \"OPENSSL_CONF=%CONDA_PREFIX%\\Library\\ssl\\openssl.cnf\"",
        };
        if (_options.Visualization || _options.Graphviz)
            lines.Add("set \"QT_QPA_PLATFORM_PLUGIN_PATH=%CONDA_PREFIX%\\Library\\plugins\\platforms\"");
        if (_options.Development) lines.Add("set \"CMAKE_GENERATOR=Visual Studio 16 2019\"");
        lines.AddRange(["call \"%~dp0local_setup.bat\"", $"set \"RMW_IMPLEMENTATION={_options.Rmw}\"", "exit /b 0"]);
        var temporary = Launcher + $".{Guid.NewGuid():N}.tmp";
        try
        {
            File.WriteAllLines(temporary, lines, Encoding.ASCII);
            File.Move(temporary, Launcher, overwrite: true);
        }
        finally { File.Delete(temporary); }
    }

    private void AddShortcut(string name, Environment.SpecialFolder folder)
    {
        var directory = Environment.GetFolderPath(folder, Environment.SpecialFolderOption.DoNotVerify);
        if (string.IsNullOrEmpty(directory))
            throw new IOException($"The current user does not have a {name} folder. Clear that shortcut option.");
        var path = Path.Combine(directory, "ROS 2 Humble Command Prompt.lnk");
        Add($"Create {name} shortcut", $"Create {path}\nTarget: {Launcher}", () =>
        {
            WindowsOperations.Shortcut(path, Launcher);
            return Task.CompletedTask;
        });
    }

    private void AddReceiverSteps(ReceiverWorkspace receiver, string source)
    {
        if (receiver.HasVerifiedBuild())
        {
            _reused.Add($"WalkableOR endpoint build at revision {ReceiverSources.Revision}");
        }
        else
        {
            var input = _offline ? source : ReceiverSources.Upstream.Url;
            Add("Prepare WalkableOR endpoint source",
                $"Verify revision {ReceiverSources.Revision} from {input}.\n" +
                $"Prepare the workspace and its config folder at {Path.GetDirectoryName(receiver.ConfigPath)}.",
                async () =>
                {
                    if (!_offline) await ReceiverSources.PrepareAsync(_scratch, source);
                    await Task.Run(() => receiver.PrepareSource(source));
                });
            Add("Build the WalkableOR receiver",
                $"Run colcon build --base-paths src --merge-install --packages-select ros_tcp_endpoint in {Path.GetDirectoryName(receiver.Launcher)}.",
                receiver.BuildAsync);
        }

        Add("Verify the WalkableOR receiver",
            "Load the overlay and check that the endpoint, PyYAML, and PointCloud2 are available.",
            receiver.VerifyAsync);
        if (_options.WalkableOrProject is { } project)
        {
            var (step, copy) = receiver.PlanConfigCopy(project, _options.ReplaceWalkableOrConfig);
            Add(step.Title, step.Detail, () => Task.Run(copy));
        }
        Add("Configure the WalkableOR launcher",
            $"Write {receiver.Launcher}. It uses the ROS command prompt's DDS setting and reads {receiver.ConfigPath}.",
            () => Task.Run(receiver.WriteLauncher));

        var desktop = Environment.GetFolderPath(Environment.SpecialFolder.DesktopDirectory, Environment.SpecialFolderOption.DoNotVerify);
        if (string.IsNullOrEmpty(desktop))
            throw new IOException("The current user does not have a desktop folder for the WalkableOR shortcut.");
        var path = Path.Combine(desktop, ReceiverLayout.ShortcutName + ".lnk");
        Add("Create Start Point Cloud Receiver shortcut", $"Create {path}\nTarget: {receiver.Launcher}", () =>
        {
            WindowsOperations.Shortcut(path, receiver.Launcher, "Start the WalkableOR Point Cloud Receiver");
            return Task.CompletedTask;
        });
    }

    private Task VerifyRosAsync() => WindowsOperations.RunAsync(new ProcessStartInfo(WindowsOperations.CommandPrompt)
    {
        Arguments = $"/d /v:off /s /c \"call \"{Launcher}\" && ros2 --help && python -c \"from rclpy import init, shutdown; from rclpy.utilities import get_rmw_implementation_identifier as rmw; init(); print(rmw()); assert rmw() == '{_options.Rmw}'; shutdown()\"\"",
        UseShellExecute = false, CreateNoWindow = true, RedirectStandardOutput = true, RedirectStandardError = true,
        WorkingDirectory = _destination
    }, _log, TimeSpan.FromMinutes(2));

    private static bool HasVcRuntime()
    {
        var system = Environment.SystemDirectory;
        return new[] { "vcruntime140_1.dll", "msvcp140.dll" }.All(name => File.Exists(Path.Combine(system, name)));
    }

    private static bool FindBuildTools()
    {
        var programFiles = Environment.GetFolderPath(Environment.SpecialFolder.ProgramFilesX86);
        var vswhere = Path.Combine(programFiles, "Microsoft Visual Studio", "Installer", "vswhere.exe");
        if (!File.Exists(vswhere)) return false;
        using var process = Process.Start(new ProcessStartInfo(vswhere)
        {
            Arguments = $"-products * -version [16.0,17.0) -requires {Compiler} {Sdk} -property installationPath",
            RedirectStandardOutput = true, UseShellExecute = false, CreateNoWindow = true
        });
        if (process is null) return false;
        var result = process.StandardOutput.ReadToEnd();
        process.WaitForExit();
        return process.ExitCode == 0 && !string.IsNullOrWhiteSpace(result);
    }

    internal static string[] BuildToolsArguments(bool offline) =>
        ["--quiet", "--wait", "--norestart", "--add", Workload, "--add", Compiler, "--add", Sdk,
            .. offline ? new[] { "--noWeb" } : Array.Empty<string>()];

    private async Task VerifyLayoutAsync(Payload vs)
    {
        var layout = Path.Combine(_payload, "vs-layout");
        await Payloads.VerifyAsync(Path.Combine(layout, vs.File), vs.Sha256);
        var indexed = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var line in await File.ReadAllLinesAsync(Path.Combine(layout, "layout.sha256")))
        {
            var parts = line.Split("  ", 2, StringSplitOptions.None);
            if (parts.Length != 2 || parts[0].Length != 64)
                throw new InvalidDataException("Invalid Visual Studio layout checksum index.");
            var full = Path.GetFullPath(Path.Combine(layout, parts[1]));
            if (!full.StartsWith(layout + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase) || !indexed.Add(full))
                throw new InvalidDataException("Invalid Visual Studio layout path.");
            await Payloads.VerifyAsync(full, parts[0]);
        }
        foreach (var file in Directory.EnumerateFiles(layout, "*", SearchOption.AllDirectories))
            if (Path.GetFileName(file) != "layout.sha256" && !indexed.Contains(file))
                throw new InvalidDataException($"Unexpected Visual Studio layout file: {file}");
        foreach (var name in new[] { vs.File, "layout.json", "Catalog.json" })
            if (!indexed.Contains(Path.Combine(layout, name))) throw new InvalidDataException($"Visual Studio layout is missing {name}.");
    }

    private static bool NeedsElevation()
    {
        using var identity = WindowsIdentity.GetCurrent();
        return !new WindowsPrincipal(identity).IsInRole(WindowsBuiltInRole.Administrator);
    }

    internal static void ValidatePlatform(bool container)
    {
        var client = (string?)Registry.GetValue(@"HKEY_LOCAL_MACHINE\SOFTWARE\Microsoft\Windows NT\CurrentVersion", "InstallationType", null);
        if (RuntimeInformation.OSArchitecture != Architecture.X64 ||
            !(client == "Client" && OperatingSystem.IsWindowsVersionAtLeast(10, 0, 22000) ||
              container && client == "Server Core" && OperatingSystem.IsWindowsVersionAtLeast(10, 0, 20348)))
            throw new PlatformNotSupportedException("Setup requires Windows 11 x64. Server Core is supported only with the container test switch.");
    }

    private static string ValidateDestination(string path)
    {
        if (!Path.IsPathFullyQualified(path) || path.StartsWith(@"\\", StringComparison.Ordinal) ||
            path.Any(character => character > 126 || character < 32 || "\"!%&<>^|;()*?".Contains(character)))
            throw new ArgumentException("Choose a full local drive path using ASCII characters and no shell metacharacters.");
        var full = Path.TrimEndingDirectorySeparator(Path.GetFullPath(path));
        var drive = new DriveInfo(Path.GetPathRoot(full)!);
        if (full == Path.TrimEndingDirectorySeparator(drive.RootDirectory.FullName) || drive.DriveType != DriveType.Fixed)
            throw new ArgumentException("Choose a folder on a local fixed drive.");
        if (drive.AvailableFreeSpace < 3L * 1024 * 1024 * 1024)
            throw new IOException("The destination drive needs at least 3 GB of free space.");
        for (var current = full; current is not null; current = Path.GetDirectoryName(current))
            if (Directory.Exists(current) && File.GetAttributes(current).HasFlag(FileAttributes.ReparsePoint))
                throw new IOException($"Choose a folder outside the junction or symbolic link at {current}.");
        return full;
    }

    private static void RequireFile(string path)
    {
        if (!File.Exists(path)) throw new FileNotFoundException($"Required file missing: {path}");
    }

    public void Dispose()
    {
        _lease?.Dispose();
        _lease = null;
        if (Directory.Exists(_scratch))
        {
            try { Directory.Delete(_scratch, recursive: true); }
            catch (IOException) { }
            catch (UnauthorizedAccessException) { }
        }
    }
}
