using System.Diagnostics;
using System.Security.Cryptography;
using System.Text;

namespace Ros2Setup;

internal sealed class ReceiverWorkspace(string rosRoot, string rosLauncher, string log)
{
    private const string OwnerMarker = ".walkableor-workspace";
    private const string BuildMarker = ".walkableor-revision";
    private const string LauncherHeader = "rem Generated by ROS 2 Humble Setup for WalkableOR";
    private readonly string _root = Path.Combine(rosRoot, ReceiverLayout.Folder);
    private string InstallPrefix => Path.Combine(_root, "install");
    private string OverlaySetup => Path.Combine(InstallPrefix, "local_setup.bat");
    private string SourcePath => Path.Combine(_root, "src", "ROS-TCP-Endpoint");
    private string RevisionPath => Path.Combine(_root, BuildMarker);
    public string ConfigPath => ReceiverLayout.ConfigPath(rosRoot);
    public string Launcher => Path.Combine(_root, "start-receiver.cmd");

    public void ValidateWorkspace()
    {
        if (!Directory.Exists(_root)) return;
        RejectLink(_root);
        var marker = Path.Combine(_root, OwnerMarker);
        if (File.Exists(marker))
        {
            RejectLink(marker);
            if (File.ReadAllText(marker) == "1")
            {
                foreach (var path in new[] { Path.Combine(_root, "src"), SourcePath,
                    Path.Combine(_root, "build"), InstallPrefix, Path.Combine(_root, "log"),
                    Path.Combine(_root, ".colcon"), RevisionPath, Launcher })
                    RejectLink(path);
                return;
            }
        }
        if (Directory.EnumerateFileSystemEntries(_root).Any())
            throw new IOException($"The installer cannot reuse the existing workspace at {_root}.");
    }

    public bool HasVerifiedBuild() =>
        File.Exists(RevisionPath) && File.ReadAllText(RevisionPath) == ReceiverSources.Revision &&
        File.Exists(OverlaySetup) &&
        File.Exists(Path.Combine(InstallPrefix, "lib", "ros_tcp_endpoint", "default_server_endpoint.exe"));

    public void PrepareSource(string archive)
    {
        ValidateWorkspace();
        Directory.CreateDirectory(_root);
        var marker = Path.Combine(_root, OwnerMarker);
        if (!File.Exists(marker)) File.WriteAllText(marker, "1");
        Directory.CreateDirectory(Path.GetDirectoryName(ConfigPath)!);

        if (Directory.Exists(SourcePath))
        {
            ReceiverSources.VerifyDirectory(SourcePath);
            return;
        }

        Directory.CreateDirectory(Path.GetDirectoryName(SourcePath)!);
        var staging = Path.Combine(_root, $".endpoint-{Guid.NewGuid():N}");
        Directory.CreateDirectory(staging);
        try
        {
            ReceiverSources.Extract(archive, staging);
            Directory.Move(staging, SourcePath);
        }
        finally
        {
            if (Directory.Exists(staging)) Directory.Delete(staging, recursive: true);
        }
    }

    public async Task BuildAsync()
    {
        ValidateWorkspace();
        File.Delete(RevisionPath);
        var start = InRosShell("colcon build --base-paths src --merge-install --packages-select ros_tcp_endpoint");
        start.Environment["COLCON_HOME"] = Path.Combine(_root, ".colcon");
        start.Environment.Remove("COLCON_DEFAULTS_FILE");
        await WindowsOperations.RunAsync(start, log, TimeSpan.FromMinutes(10));
    }

    public async Task VerifyAsync()
    {
        ValidateWorkspace();
        ReceiverSources.VerifyDirectory(SourcePath);
        var start = InRosShell($"""
            call "{OverlaySetup}" && python -c "import os; import yaml; from sensor_msgs.msg import PointCloud2; from ament_index_python.packages import get_package_prefix; assert os.path.samefile(get_package_prefix('ros_tcp_endpoint'), os.environ['WALKABLEOR_INSTALL'])" && ros2 run ros_tcp_endpoint default_server_endpoint --help
            """);
        start.Environment["WALKABLEOR_INSTALL"] = InstallPrefix;
        await WindowsOperations.RunAsync(start, log, TimeSpan.FromMinutes(2));
        File.WriteAllText(RevisionPath, ReceiverSources.Revision);
    }

    public (Step Step, Action Copy) PlanConfigCopy(string project, bool replace)
    {
        var source = ReceiverLayout.ConfigPath(Path.GetFullPath(project));
        if (!File.Exists(source))
            throw new ArgumentException($"No walkableOR.yaml was found at {source}. Select the walkableOR_unity project folder or supply the file later.");

        var sourceHash = ConfigHash(source);
        var existingHash = ReadConfigHash();
        if (!replace && existingHash is not null && !existingHash.SequenceEqual(sourceHash))
            throw ConfigConflict();

        var detail = $"Source: {source}\nDestination: {ConfigPath}";
        if (replace && existingHash is not null) detail += "\nThis replaces the existing configuration if its contents differ.";
        return (new Step("Copy the WalkableOR configuration", detail),
            () => CopyConfig(source, existingHash, replace));
    }

    private void CopyConfig(string source, byte[]? expectedHash, bool replace)
    {
        ValidateWorkspace();
        var directory = Path.GetDirectoryName(ConfigPath)!;
        RejectLink(directory);
        Directory.CreateDirectory(directory);
        var temporary = ConfigPath + $".{Guid.NewGuid():N}.tmp";
        try
        {
            using (var input = File.OpenRead(source))
            using (var output = new FileStream(temporary, FileMode.CreateNew, FileAccess.Write))
                input.CopyTo(output);

            var currentHash = ReadConfigHash();
            if (currentHash is not null)
            {
                if (currentHash.SequenceEqual(ConfigHash(temporary))) return;
                if (!replace) throw ConfigConflict();
                if (expectedHash is null || !currentHash.SequenceEqual(expectedHash))
                    throw new IOException($"The configuration at {ConfigPath} changed after review. Reopen setup to review it again.");
            }
            File.Move(temporary, ConfigPath, overwrite: currentHash is not null);
        }
        finally { File.Delete(temporary); }
    }

    private byte[]? ReadConfigHash()
    {
        RejectLink(Path.GetDirectoryName(ConfigPath)!);
        RejectLink(ConfigPath);
        if (Directory.Exists(ConfigPath))
            throw new IOException($"A folder occupies the receiver configuration path {ConfigPath}.");
        return File.Exists(ConfigPath) ? ConfigHash(ConfigPath) : null;
    }

    private static byte[] ConfigHash(string path)
    {
        using var input = File.OpenRead(path);
        return SHA256.HashData(input);
    }

    private IOException ConfigConflict() =>
        new($"A different receiver configuration already exists at {ConfigPath}. Select the replacement option to update it, or supply the configuration later to keep it.");

    public void WriteLauncher()
    {
        ValidateWorkspace();
        if (File.Exists(Launcher) && !File.ReadLines(Launcher).Take(2).Contains(LauncherHeader))
            throw new IOException($"A different launcher already exists at {Launcher}.");
        string[] lines =
        [
            "@echo off", LauncherHeader, "setlocal DisableDelayedExpansion",
            "for %%I in (\"%~dp0configs\\walkableOR.yaml\") do set \"CONFIG=%%~fI\"",
            """
            if not exist "%CONFIG%" goto missing
            if exist "%CONFIG%\" goto missing
            pushd "%~dp0" || exit /b 1
            call "%~dp0..\ros-humble.cmd" || goto setup_failed
            set "WALKABLEOR_RMW=%RMW_IMPLEMENTATION%"
            call "%~dp0install\local_setup.bat" || goto setup_failed
            set "RMW_IMPLEMENTATION=%WALKABLEOR_RMW%"
            if not defined ROS_DOMAIN_ID set "ROS_DOMAIN_ID=0"
            set "ROS_LOCALHOST_ONLY=0"
            set "PYTHONUNBUFFERED=1"
            echo WalkableOR Point Cloud Receiver
            echo Config "%CONFIG%"
            echo DDS %RMW_IMPLEMENTATION%, ROS domain %ROS_DOMAIN_ID%, Unity TCP 127.0.0.1:10000
            ros2 run ros_tcp_endpoint default_server_endpoint "%CONFIG%" --ros-args -p ROS_IP:=127.0.0.1 -p ROS_TCP_PORT:=10000
            set "RECEIVER_EXIT=%ERRORLEVEL%"
            popd
            exit /b %RECEIVER_EXIT%

            :missing
            echo Missing WalkableOR configuration. 1>&2
            echo Copy your walkableOR.yaml to "%CONFIG%" before starting the receiver. 1>&2
            exit /b 2

            :setup_failed
            echo Could not load the ROS 2 Humble or WalkableOR workspace. 1>&2
            popd
            exit /b 1
            """
        ];
        var temporary = Launcher + $".{Guid.NewGuid():N}.tmp";
        try
        {
            File.WriteAllLines(temporary, lines.Select(line => line.ReplaceLineEndings("\r\n")), Encoding.ASCII);
            File.Move(temporary, Launcher, overwrite: true);
        }
        finally { File.Delete(temporary); }
    }

    private ProcessStartInfo InRosShell(string command) => new(WindowsOperations.CommandPrompt)
    {
        Arguments = $"/d /v:off /s /c \"call \"{rosLauncher}\" && {command}\"",
        WorkingDirectory = _root, UseShellExecute = false, CreateNoWindow = true,
        RedirectStandardOutput = true, RedirectStandardError = true
    };

    private static void RejectLink(string path)
    {
        if ((Directory.Exists(path) || File.Exists(path)) && File.GetAttributes(path).HasFlag(FileAttributes.ReparsePoint))
            throw new IOException($"The receiver workspace cannot use the link at {path}.");
    }
}
