using System.Reflection;

namespace Ros2Setup;

internal static class UninstallerFiles
{
    private const string ScriptName = "uninstall-ros-humble.ps1";
    public const string ShellMonitorName = "ros-shells.ps1";
    private const string Header = "Generated by ROS 2 Humble Setup";

    public static void Write(string root, string release)
    {
        var script = ReadScript(ScriptName).Replace("@ROS_RELEASE@", release, StringComparison.Ordinal);
        var launcher = $$"""
            @echo off
            rem {{Header}}
            start "Uninstall ROS 2 Humble" /d "%TEMP%" "%SystemRoot%\System32\WindowsPowerShell\v1.0\powershell.exe" -NoLogo -NoProfile -STA -WindowStyle Hidden -ExecutionPolicy RemoteSigned -File "%~dp0{{ScriptName}}"
            """;
        var scriptPath = Path.Combine(root, ScriptName);
        var launcherPath = Path.Combine(root, UninstallLayout.LauncherName);
        var monitorPath = Path.Combine(root, ShellMonitorName);
        RequireOwnedOrNew(scriptPath, "# " + Header);
        RequireOwnedOrNew(launcherPath, "rem " + Header);
        RequireOwnedOrNew(monitorPath, "# " + Header);
        WriteFile(monitorPath, ReadScript(ShellMonitorName));
        WriteFile(scriptPath, script);
        WriteFile(launcherPath, launcher);
    }

    private static string ReadScript(string name)
    {
        using var resource = Assembly.GetExecutingAssembly().GetManifestResourceStream(name)!;
        using var reader = new StreamReader(resource);
        return reader.ReadToEnd();
    }

    private static void RequireOwnedOrNew(string path, string header)
    {
        if (File.Exists(path) && (File.GetAttributes(path).HasFlag(FileAttributes.ReparsePoint) ||
            !File.ReadLines(path).Take(2).Contains(header)))
            throw new IOException($"An unrelated file already exists at {path}.");
    }

    private static void WriteFile(string path, string content)
    {
        var temporary = path + $".{Guid.NewGuid():N}.tmp";
        try
        {
            File.WriteAllText(temporary, content.ReplaceLineEndings("\r\n") + "\r\n");
            File.Move(temporary, path, overwrite: true);
        }
        finally { File.Delete(temporary); }
    }
}
